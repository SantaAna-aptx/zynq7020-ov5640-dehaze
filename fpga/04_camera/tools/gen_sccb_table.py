# -*- coding: utf-8 -*-
"""Generate the OV5640 SCCB register ROM from a plain text register list.

Source of truth
    ov5640_640x480_rgb565.reg      "0xRRRR 0xVV" per line, written by
                                   extract_ref_regs.py from the working vendor
                                   demo. Contains a `RESOLUTION W H` line.

Emitted
    ../rtl/ov5640_init_rom.v       a *block-RAM* ROM (registered read, contents
                                   from an initial block). Deliberately not a
                                   `case` table: 251 entries x 24 bit as
                                   combinational logic is ~1k LUTs of pure waste
                                   on a design that is already LUT-tight.
    ../tb/ov5640_init_sim.hex      the same data as hex, for the testbench
    ../rtl/ov5640_init.hex         kept for reference / diffing

Entry packing is 24 bits: { reg[15:8], reg[7:0], data[7:0] }. 0xFFFFFF ends it.

Why a generated Verilog ROM and not $readmemh: a hex file has to be found
relative to the synthesis tool's working directory, which is a classic
"elaborated fine, synthesised an empty ROM" trap. Generating Verilog removes
the file-system dependency completely.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))       # -> fpga/

REG_LIST    = os.path.join(HERE, "ov5640_640x480_rgb565.reg")
ROM_VERILOG = os.path.join(ROOT, "04_camera", "rtl", "ov5640_init_rom.v")
HEX_SIM     = os.path.join(ROOT, "04_camera", "tb", "ov5640_init_sim.hex")
HEX_REF     = os.path.join(ROOT, "04_camera", "rtl", "ov5640_init.hex")

ROM_DEPTH = 512          # 9-bit index; must be > number of entries


def load():
    """-> (entries, (w, h)) with {W}/{H} expanded."""
    entries = []
    width, height = 640, 480
    with open(REG_LIST, encoding="utf-8") as f:
        for lineno, raw in enumerate(f, 1):
            s = raw.split("#", 1)[0].strip()
            if not s:
                continue
            parts = s.split()
            if parts[0].upper() == "RESOLUTION":
                width, height = int(parts[1]), int(parts[2])
                continue
            if len(parts) != 2:
                raise SystemExit(f"{REG_LIST}:{lineno}: expected '0xRRRR 0xVV'")
            reg = int(parts[0], 16)
            expr = parts[1].replace("{W}", str(width)).replace("{H}", str(height))
            val = eval(expr, {"__builtins__": {}}, {}) & 0xFF
            if not (0 <= reg <= 0xFFFF):
                raise SystemExit(f"{REG_LIST}:{lineno}: register out of range")
            entries.append((reg, val))
    if len(entries) > ROM_DEPTH - 1:
        raise SystemExit(f"table has {len(entries)} entries, ROM is {ROM_DEPTH}")
    return entries, (width, height)


def packed(entries):
    return [((reg << 8) | data) & 0xFFFFFF for reg, data in entries]


def write_hex(path, vals):
    lines = [f"{v:06x}" for v in vals] + ["ffffff"]
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path}: {len(vals)} entries")


def write_rom(path, vals, res):
    w, h = res
    o = []
    o.append("// Auto-generated by 04_camera/tools/gen_sccb_table.py -- do not edit.")
    o.append("//")
    o.append(f"// OV5640 DVP RGB565 initialisation table, {w}x{h}, {len(vals)} writes.")
    o.append("// Source: 04_camera/tools/ov5640_640x480_rgb565.reg")
    o.append("//")
    o.append("// A block RAM with a registered read port, not a `case` table: the")
    o.append("// combinational version of this ROM costs roughly a thousand LUTs, which")
    o.append("// matters on a design that is already close to the device limit. The read")
    o.append("// port is synchronous, so ov5640_sccb.v spends one state on the fetch.")
    o.append("`timescale 1ns / 1ps")
    o.append("")
    o.append(f"module ov5640_init_rom (")
    o.append("    input  wire       clk,")
    o.append("    input  wire [8:0] idx,")
    o.append("    output reg  [23:0] dout")
    o.append(");")
    o.append("")
    o.append(f"    (* rom_style = \"block\" *) reg [23:0] mem [0:{ROM_DEPTH - 1}];")
    o.append("")
    o.append("    initial begin")
    for i, v in enumerate(vals):
        o.append(f"        mem[{i}] = 24'h{v:06x};")
    for i in range(len(vals), ROM_DEPTH):
        o.append(f"        mem[{i}] = 24'hffffff;   // end of table")
    o.append("    end")
    o.append("")
    o.append("    always @(posedge clk) dout <= mem[idx];")
    o.append("")
    o.append("endmodule")
    o.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(o))
    print(f"wrote {path}: {len(vals)} entries in a {ROM_DEPTH}x24 block ROM")


def main():
    entries, res = load()
    vals = packed(entries)
    print(f"resolution {res[0]}x{res[1]}, {len(entries)} register writes")
    write_rom(ROM_VERILOG, vals, res)
    write_hex(HEX_SIM, vals)
    write_hex(HEX_REF, vals)


if __name__ == "__main__":
    main()
